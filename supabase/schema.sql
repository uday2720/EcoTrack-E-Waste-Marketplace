-- ------------------------------------------------------------------------------
-- 1. PROFILES TABLE (Linked with auth.users)
-- ------------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text not null,
  email text,
  phone text,
  location text,
  role text not null check (role in ('buyer', 'seller', 'admin')) default 'buyer',
  status text not null check (status in ('active', 'blocked')) default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Index for role-based lookups
create index if not exists idx_profiles_role on public.profiles(role);
create index if not exists idx_profiles_status on public.profiles(status);

-- Automatic profile sync trigger from Supabase Auth
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, email, phone, location, role, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.email,
    new.raw_user_meta_data->>'phone',
    new.raw_user_meta_data->>'location',
    coalesce(new.raw_user_meta_data->>'role', 'buyer'),
    'active'
  )
  on conflict (id) do update set
    full_name = coalesce(excluded.full_name, profiles.full_name),
    email = coalesce(excluded.email, profiles.email),
    role = coalesce(excluded.role, profiles.role),
    updated_at = now();
  return new;
end;
$$ language plpgsql security definer;

-- Trigger definition
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Trigger to prevent privilege escalation (cannot promote self to admin or unblock self)
create or replace function public.protect_profile_roles()
returns trigger as $$
begin
  if (new.role = 'admin' and (old.role is null or old.role <> 'admin')) or
     (new.status <> coalesce(old.status, 'active')) then
    if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') then
      raise exception 'Unauthorized role or status modification';
    end if;
  end if;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists trg_protect_profile_roles on public.profiles;
create trigger trg_protect_profile_roles
  before update on public.profiles
  for each row execute function public.protect_profile_roles();

-- ------------------------------------------------------------------------------
-- 2. PRODUCTS TABLE
-- ------------------------------------------------------------------------------
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  seller_id uuid references public.profiles(id) on delete cascade not null,
  title text not null check (char_length(title) >= 3),
  category text not null check (category in ('Laptops', 'Phones', 'Monitors', 'Accessories', 'Printers', 'Other')),
  price numeric(10,2) not null check (price > 0),
  condition text not null check (condition in ('Like new', 'Good', 'Used', 'Fair', 'For parts')),
  location text,
  description text,
  specs text,
  image_url text,
  status text not null check (status in ('available', 'reserved', 'sold', 'deleted')) default 'available',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_products_status on public.products(status);
create index if not exists idx_products_category on public.products(category);
create index if not exists idx_products_seller_id on public.products(seller_id);
create index if not exists idx_products_created_at on public.products(created_at desc);

-- ------------------------------------------------------------------------------
-- 3. CONVERSATIONS TABLE
-- ------------------------------------------------------------------------------
create table if not exists public.conversations (
  id uuid default gen_random_uuid() primary key,
  product_id bigint references public.products(id) on delete set null,
  buyer_id uuid references public.profiles(id) on delete cascade not null,
  seller_id uuid references public.profiles(id) on delete cascade not null,
  final_price numeric(10,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_conversation_product_buyer unique (product_id, buyer_id),
  constraint chk_different_parties check (buyer_id <> seller_id)
);

create index if not exists idx_conversations_buyer on public.conversations(buyer_id);
create index if not exists idx_conversations_seller on public.conversations(seller_id);

-- ------------------------------------------------------------------------------
-- 4. MESSAGES TABLE
-- ------------------------------------------------------------------------------
create table if not exists public.messages (
  id uuid default gen_random_uuid() primary key,
  conversation_id uuid references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  body text not null check (trim(body) <> ''),
  created_at timestamptz not null default now()
);

create index if not exists idx_messages_conversation on public.messages(conversation_id, created_at asc);

-- ------------------------------------------------------------------------------
-- 5. PRICE OFFERS TABLE
-- ------------------------------------------------------------------------------
create table if not exists public.price_offers (
  id uuid default gen_random_uuid() primary key,
  conversation_id uuid references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  amount numeric(10,2) not null check (amount > 0),
  status text not null check (status in ('pending', 'accepted', 'rejected', 'countered', 'cancelled')) default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_price_offers_conversation on public.price_offers(conversation_id);

-- ------------------------------------------------------------------------------
-- 6. ORDERS & ESCROW TABLE
-- ------------------------------------------------------------------------------
create table if not exists public.orders (
  id uuid default gen_random_uuid() primary key,
  order_number text unique not null,
  product_id bigint references public.products(id) on delete set null,
  buyer_id uuid references public.profiles(id) on delete cascade not null,
  seller_id uuid references public.profiles(id) on delete cascade not null,
  offer_id uuid references public.price_offers(id) on delete set null,
  product_price numeric(10,2) not null check (product_price > 0),
  delivery_fee numeric(10,2) not null default 200,
  platform_fee numeric(10,2) not null default 11,
  total_paid numeric(10,2) not null,
  seller_payout numeric(10,2) not null,
  status text not null check (
    status in ('awaiting_payment', 'escrow_held', 'shipped', 'delivered', 'approved', 'completed', 'cancelled', 'disputed')
  ) default 'awaiting_payment',
  buyer_approved boolean not null default false,
  payment_method text default 'simulated_escrow',
  delivery_address text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_orders_buyer on public.orders(buyer_id);
create index if not exists idx_orders_seller on public.orders(seller_id);
create index if not exists idx_orders_status on public.orders(status);

-- ------------------------------------------------------------------------------
-- 7. ATOMIC TRANSACTION RPC: RESPOND TO PRICE OFFER
-- ------------------------------------------------------------------------------
create or replace function public.respond_to_price_offer(
  p_offer_id uuid,
  p_action text,
  p_counter_amount numeric default null
)
returns json as $$
declare
  v_offer record;
  v_conv record;
  v_caller uuid := auth.uid();
  v_new_offer_id uuid;
begin
  select * into v_offer from public.price_offers where id = p_offer_id for update;
  if not found then
    raise exception 'Offer not found';
  end if;

  select * into v_conv from public.conversations where id = v_offer.conversation_id for update;
  if not found then
    raise exception 'Conversation not found';
  end if;

  if v_caller <> v_conv.buyer_id and v_caller <> v_conv.seller_id then
    raise exception 'Unauthorized to respond to this offer';
  end if;

  if p_action = 'accept' then
    update public.price_offers set status = 'accepted', updated_at = now() where id = p_offer_id;
    update public.conversations set final_price = v_offer.amount, updated_at = now() where id = v_conv.id;
    return json_build_object('success', true, 'status', 'accepted', 'final_price', v_offer.amount);

  elsif p_action = 'reject' then
    update public.price_offers set status = 'rejected', updated_at = now() where id = p_offer_id;
    return json_build_object('success', true, 'status', 'rejected');

  elsif p_action = 'counter' then
    if p_counter_amount is null or p_counter_amount <= 0 then
      raise exception 'Counter offer amount must be greater than zero';
    end if;

    update public.price_offers set status = 'countered', updated_at = now() where id = p_offer_id;

    insert into public.price_offers (conversation_id, sender_id, amount, status)
    values (v_conv.id, v_caller, p_counter_amount, 'pending')
    returning id into v_new_offer_id;

    return json_build_object('success', true, 'status', 'countered', 'new_offer_id', v_new_offer_id);
  else
    raise exception 'Invalid action: %', p_action;
  end if;
end;
$$ language plpgsql security definer;

-- ------------------------------------------------------------------------------
-- 8. ATOMIC ORDER CREATION RPC (Prevents Race Conditions & Duplicate Purchases)
-- ------------------------------------------------------------------------------
create or replace function public.create_escrow_order(
  p_product_id bigint,
  p_offer_id uuid default null,
  p_agreed_price numeric default null,
  p_delivery_fee numeric default 200,
  p_delivery_address text default null
)
returns json as $$
declare
  v_product record;
  v_buyer_id uuid := auth.uid();
  v_buyer_profile record;
  v_offer record;
  v_conv record;
  v_product_price numeric;
  v_delivery_fee numeric;
  v_buyer_delivery numeric;
  v_platform_fee numeric := 11.00;
  v_total_paid numeric;
  v_seller_payout numeric;
  v_order_id uuid;
  v_order_number text;
begin
  if v_buyer_id is null then
    raise exception 'Authentication required to create an order';
  end if;

  select * into v_buyer_profile from public.profiles where id = v_buyer_id;
  if not found or v_buyer_profile.status = 'blocked' then
    raise exception 'Account is not authorized or is blocked';
  end if;

  -- Lock product record to avoid race conditions
  select * into v_product from public.products where id = p_product_id for update;
  if not found then
    raise exception 'Product not found';
  end if;

  if v_product.status <> 'available' then
    raise exception 'Product is no longer available for purchase (status: %)', v_product.status;
  end if;

  if v_product.seller_id = v_buyer_id then
    raise exception 'You cannot purchase your own listed product';
  end if;

  -- Server-side price validation: prevent client-side price tampering
  if p_offer_id is not null then
    select * into v_offer from public.price_offers where id = p_offer_id;
    if not found or v_offer.status <> 'accepted' then
      raise exception 'The negotiated offer is invalid or has not been accepted';
    end if;

    select * into v_conv from public.conversations where id = v_offer.conversation_id;
    if not found or v_conv.buyer_id <> v_buyer_id or v_conv.product_id <> p_product_id then
      raise exception 'Offer does not correspond to this buyer and product';
    end if;

    v_product_price := v_offer.amount;
  else
    -- When buying directly without an offer, price must be the listed asking price
    v_product_price := v_product.price;
  end if;

  -- Validate delivery fee bounds (0 to 5000)
  v_delivery_fee := greatest(0::numeric, least(5000::numeric, coalesce(p_delivery_fee, 200::numeric)));
  v_buyer_delivery := v_delivery_fee / 2.0;
  v_total_paid := v_product_price + v_buyer_delivery + v_platform_fee;
  v_seller_payout := greatest(0::numeric, v_product_price - v_buyer_delivery - v_platform_fee);

  v_order_number := 'ET-' || to_char(now(), 'YYYYMMDD') || '-' || upper(substring(gen_random_uuid()::text from 1 for 6));

  -- Insert order in escrow state
  insert into public.orders (
    order_number, product_id, buyer_id, seller_id, offer_id,
    product_price, delivery_fee, platform_fee, total_paid, seller_payout,
    status, buyer_approved, delivery_address
  )
  values (
    v_order_number, p_product_id, v_buyer_id, v_product.seller_id, p_offer_id,
    v_product_price, v_delivery_fee, v_platform_fee, v_total_paid, v_seller_payout,
    'escrow_held', false, p_delivery_address
  )
  returning id into v_order_id;

  -- Atomically reserve product
  update public.products
  set status = 'reserved', updated_at = now()
  where id = p_product_id;

  return json_build_object(
    'success', true,
    'order_id', v_order_id,
    'order_number', v_order_number,
    'total_paid', v_total_paid,
    'seller_payout', v_seller_payout,
    'status', 'escrow_held'
  );
end;
$$ language plpgsql security definer;

