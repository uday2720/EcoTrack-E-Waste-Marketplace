-- Profiles policies
create policy "Public profiles are viewable by anyone"
  on public.profiles for select using (true);

create policy "Users can update their own profile"
  on public.profiles for update using (auth.uid() = id);

-- Products policies
create policy "Available products are viewable by everyone"
  on public.products for select
  using (status in ('available', 'reserved', 'sold') or auth.uid() = seller_id);

create policy "Only sellers can create products"
  on public.products for insert
  with check (
    auth.uid() = seller_id and
    exists (select 1 from public.profiles where id = auth.uid() and role in ('seller', 'admin'))
  );

create policy "Sellers can update their own products"
  on public.products for update
  using (auth.uid() = seller_id);

create policy "Sellers can delete their own products"
  on public.products for delete
  using (auth.uid() = seller_id);

-- Conversations policies
create policy "Participants can view their conversations"
  on public.conversations for select
  using (auth.uid() in (buyer_id, seller_id));

create policy "Buyers can initiate conversations"
  on public.conversations for insert
  with check (auth.uid() = buyer_id);

create policy "Participants can update conversations"
  on public.conversations for update
  using (auth.uid() in (buyer_id, seller_id));

-- Messages policies
create policy "Conversation participants can read messages"
  on public.messages for select
  using (
    exists (
      select 1 from public.conversations c
      where c.id = messages.conversation_id
      and auth.uid() in (c.buyer_id, c.seller_id)
    )
  );

create policy "Conversation participants can insert messages"
  on public.messages for insert
  with check (
    auth.uid() = sender_id and
    exists (
      select 1 from public.conversations c
      where c.id = messages.conversation_id
      and auth.uid() in (c.buyer_id, c.seller_id)
    )
  );

-- Price offers policies
create policy "Conversation participants can read offers"
  on public.price_offers for select
  using (
    exists (
      select 1 from public.conversations c
      where c.id = price_offers.conversation_id
      and auth.uid() in (c.buyer_id, c.seller_id)
    )
  );

create policy "Conversation participants can insert offers"
  on public.price_offers for insert
  with check (
    auth.uid() = sender_id and
    exists (
      select 1 from public.conversations c
      where c.id = price_offers.conversation_id
      and auth.uid() in (c.buyer_id, c.seller_id)
    )
  );

-- Orders policies
create policy "Buyers, sellers, and admins can view orders"
  on public.orders for select
  using (
    auth.uid() in (buyer_id, seller_id) or
    exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
  );

create policy "Buyers can mark order approved upon receipt"
  on public.orders for update
  using (auth.uid() = buyer_id or exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'))
  with check (
    (auth.uid() = buyer_id and status in ('delivered', 'approved')) or
    exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
  );

create policy "Sellers can update order shipment status"
  on public.orders for update
  using (
    auth.uid() = seller_id or
    exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
  )
  with check (
    (auth.uid() = seller_id and status in ('shipped', 'delivered')) or
    exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
  );

